-- Conector de e-mail multiusuário (Nylas no MVP, modelo neutro por provedor).
-- Dados sensíveis são acessados somente pelo backend com service_role.

CREATE TABLE public.email_connections (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  provider text NOT NULL DEFAULT 'nylas',
  provider_grant_id text NOT NULL,
  provider_account_email text,
  provider_name text,
  status text NOT NULL DEFAULT 'connected'
    CHECK (status IN ('connected', 'reauth_required', 'revoked', 'error')),
  scopes text,
  connected_at timestamptz NOT NULL DEFAULT now(),
  last_sync_at timestamptz,
  last_error text,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (provider, provider_grant_id)
);

CREATE INDEX email_connections_user_status_idx
  ON public.email_connections (user_id, status, updated_at DESC);

CREATE TABLE public.email_oauth_states (
  state text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  provider text NOT NULL DEFAULT 'nylas',
  requested_connector text,
  redirect_uri text NOT NULL,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX email_oauth_states_expiry_idx
  ON public.email_oauth_states (expires_at) WHERE used_at IS NULL;

CREATE TABLE public.email_verification_codes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  connection_id uuid NOT NULL REFERENCES public.email_connections(id) ON DELETE CASCADE,
  owner_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  provider_message_id text NOT NULL,
  sender_email text NOT NULL,
  subject text,
  code_ciphertext text,
  code_iv text,
  code_length integer NOT NULL CHECK (code_length BETWEEN 4 AND 16),
  received_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  first_revealed_at timestamptz,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (connection_id, provider_message_id)
);

CREATE INDEX email_codes_owner_recent_idx
  ON public.email_verification_codes (owner_user_id, received_at DESC);
CREATE INDEX email_codes_active_idx
  ON public.email_verification_codes (expires_at DESC)
  WHERE used_at IS NULL AND code_ciphertext IS NOT NULL;

CREATE TABLE public.email_code_access_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code_id uuid REFERENCES public.email_verification_codes(id) ON DELETE SET NULL,
  actor_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  owner_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  action text NOT NULL CHECK (action IN ('list', 'reveal', 'copy', 'mark_used', 'disconnect', 'manual_sync')),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX email_code_audit_actor_idx
  ON public.email_code_access_audit (actor_user_id, created_at DESC);
CREATE INDEX email_code_audit_owner_idx
  ON public.email_code_access_audit (owner_user_id, created_at DESC);

CREATE TABLE public.email_webhook_events (
  event_id text PRIMARY KEY,
  event_type text NOT NULL,
  provider text NOT NULL DEFAULT 'nylas',
  provider_grant_id text,
  provider_object_id text,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'processed', 'ignored', 'failed')),
  attempts integer NOT NULL DEFAULT 0,
  last_error text,
  processed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX email_webhook_events_pending_idx
  ON public.email_webhook_events (status, created_at)
  WHERE status IN ('pending', 'failed');

ALTER TABLE public.email_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.email_oauth_states ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.email_verification_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.email_code_access_audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.email_webhook_events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.email_connections FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.email_oauth_states FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.email_verification_codes FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.email_code_access_audit FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.email_webhook_events FROM PUBLIC, anon, authenticated;

GRANT ALL ON public.email_connections TO service_role;
GRANT ALL ON public.email_oauth_states TO service_role;
GRANT ALL ON public.email_verification_codes TO service_role;
GRANT ALL ON public.email_code_access_audit TO service_role;
GRANT ALL ON public.email_webhook_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.email_code_access_audit_id_seq TO service_role;

COMMENT ON TABLE public.email_connections IS
  'Conexões de caixas postais. provider_grant_id nunca é exposto diretamente ao navegador.';
COMMENT ON TABLE public.email_verification_codes IS
  'Códigos temporários criptografados no backend; nenhum corpo de e-mail é persistido.';
COMMENT ON TABLE public.email_code_access_audit IS
  'Auditoria imutável de revelação e operações sensíveis sobre códigos de autenticação.';

